"""Data containers for random sample generation steps."""

from dataclasses import dataclass

from pysatl_criterion.generator.model import AbstractRVSGenerator


@dataclass
class GenerationData:
    """
    Configuration for random sample generation.

    Attributes
    ----------
    generator : AbstractRVSGenerator
        Generator instance.
    sample_size : int
        Size of generated samples.
    samples_count : int
        Number of samples to generate.
    generator_code : str
        Stable sample-series code including the configured parameter ranges.
    """

    generator: AbstractRVSGenerator
    sample_size: int
    samples_count: int
    generator_code: str


@dataclass
class GenerationStepContext:
    """
    Configuration for random sample generation.

    Attributes
    ----------
    data_list : list[GenerationData]
    experiment_name : str
    parallel_workers : int
        Number of parallel worker processes.
    samples_per_task : int
        Maximum number of samples generated by one worker task.
    write_batch_size : int
        Maximum number of samples saved in one storage batch.
    """

    data_list: list[GenerationData]
    experiment_name: str
    parallel_workers: int = 1
    samples_per_task: int = 500
    write_batch_size: int = 1000

    def __post_init__(self) -> None:
        """Require positive integer limits for computation and storage batches."""
        for name in ("samples_per_task", "write_batch_size"):
            value = getattr(self, name)
            if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
                raise ValueError(f"{name} must be a positive integer")
