"""
Random values persistence layer (SQLAlchemy implementation).

This module provides database models and storage implementation for
random value samples generated by configurable generators.
"""

from __future__ import annotations

import json
from collections.abc import Iterable
from typing import ClassVar

from pysatl_criterion.persistence.sqlalchemy.alchemy_decorator import CompressedFloatArray
from sqlalchemy import Integer, String, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column
from typing_extensions import override

from pysatl_experiment.persistence.db_store.base import ModelBase, SessionType
from pysatl_experiment.persistence.db_store.model import AbstractDbStore
from pysatl_experiment.persistence.models.random_values import (
    IRandomValuesStorage,
    RandomValuesAllModel,
    RandomValuesAllQuery,
    RandomValuesCountQuery,
    RandomValuesModel,
    RandomValuesQuery,
)


class AlchemyRandomValues(ModelBase):
    """
    SQLAlchemy ORM model for stored random value samples.

    Attributes
    ----------
    id : int
        Primary key.
    generator_code : str
        Name of generator.
    generator_parameters : str
        JSON-encoded generator parameters.
    sample_size : int
        Size of generated sample.
    experiment_name : str
        Sequential sample index.
    data : list[float]
        Generated random values.

    Notes
    -----
    Uniqueness is enforced by (generator_code, generator_parameters,
    sample_size, experiment_name).
    """

    __tablename__ = "random_values"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)  # type: ignore
    generator_code: Mapped[str] = mapped_column(String, nullable=False, index=True)  # type: ignore
    generator_parameters: Mapped[str] = mapped_column(String, nullable=False)  # type: ignore
    sample_size: Mapped[int] = mapped_column(Integer, nullable=False, index=True)  # type: ignore
    experiment_name: Mapped[str] = mapped_column(String, nullable=False, index=True)  # type: ignore
    sample_num: Mapped[int] = mapped_column(Integer, nullable=False, index=True, default=1)  # type: ignore
    data: Mapped[list[float]] = mapped_column(CompressedFloatArray(), nullable=False)  # type: ignore

    __table_args__ = (
        UniqueConstraint(
            "generator_code",
            "sample_size",
            "experiment_name",
            "sample_num",
            name="uq_random_values_unique",
        ),
    )


class AlchemyRandomValuesStorage(AbstractDbStore, IRandomValuesStorage):
    """
    SQLAlchemy storage for random value samples.

    Attributes
    ----------
    session : SessionType
        Shared SQLAlchemy session.
    _initialized : bool
        Initialization flag.
    """

    session: ClassVar[SessionType]

    def __init__(self, db_url: str):
        """
        Initialize random values storage.

        Parameters
        ----------
        db_url : str
            Database connection string.
        """
        super().__init__(db_url=db_url)
        self._initialized: bool = False

    def init(self) -> None:
        """
        Initialize the database engine and scoped session.

        Must be called before any storage operation.
        Sets the internal ``_initialized`` flag to ensure a session is available.
        """
        # Initialize engine and scoped session via AbstractDbStore
        super().init()
        self._initialized = True

    def _get_session(self) -> SessionType:
        """
        Return the active SQLAlchemy session.

        Returns
        -------
        SessionType
            SQLAlchemy session used for executing queries.

        Raises
        ------
        RuntimeError
            If the storage has not been initialized.
        """
        if not getattr(self, "_initialized", False):
            raise RuntimeError("Storage not initialized. Call init() first.")
        # Access class attribute defined by AbstractDbStore after init()
        return AlchemyRandomValuesStorage.session

    def get_data(self, query: RandomValuesQuery) -> RandomValuesModel | None:
        """
        Fetch single sample by full key.

        Parameters
        ----------
        query : RandomValuesQuery
            Query object defining generator name, parameters,
            sample size and sample number.

        Returns
        -------
        RandomValuesModel | None
            Stored sample if found, otherwise None.
        """
        row: AlchemyRandomValues | None = (
            self._get_session()
            .query(AlchemyRandomValues)
            .filter(
                AlchemyRandomValues.generator_code == query.generator_code,
                AlchemyRandomValues.sample_size == int(query.sample_size),
                AlchemyRandomValues.experiment_name == query.experiment_name,
            )
            .one_or_none()
        )

        if row is None:
            return None

        return RandomValuesModel(
            generator_code=row.generator_code,
            generator_parameters=json.loads(row.generator_parameters),
            sample_size=row.sample_size,
            experiment_name=self._model_experiment_name(row),
            data=row.data,
        )

    def insert_data(self, data: RandomValuesModel) -> None:
        """
        Insert or update a random value sample.

        Parameters
        ----------
        data : RandomValuesModel
            Sample to store or update.

        Returns
        -------
        None
        """
        params_json = json.dumps(data.generator_parameters)
        entity = AlchemyRandomValues(
            generator_code=data.generator_code,
            generator_parameters=params_json,
            sample_size=int(data.sample_size),
            experiment_name=data.experiment_name,
            sample_num=self._sample_num_from_experiment_name(data.experiment_name),
            data=data.data,
        )
        existing: AlchemyRandomValues | None = (
            self._get_session()
            .query(AlchemyRandomValues)
            .filter(
                AlchemyRandomValues.generator_code == entity.generator_code,
                AlchemyRandomValues.sample_size == entity.sample_size,
                AlchemyRandomValues.experiment_name == entity.experiment_name,
                AlchemyRandomValues.sample_num == entity.sample_num,
            )
            .one_or_none()
        )
        if existing is None:
            self._get_session().add(entity)
        else:
            existing.data = entity.data
        self._get_session().commit()

    def delete_data(self, query: RandomValuesQuery) -> None:
        """
        Delete a sample.

        Parameters
        ----------
        query : RandomValuesQuery
            Identifies sample to delete.

        Returns
        -------
        None
        """
        (
            self._get_session()
            .query(AlchemyRandomValues)
            .filter(
                AlchemyRandomValues.generator_code == query.generator_code,
                AlchemyRandomValues.sample_size == int(query.sample_size),
                AlchemyRandomValues.experiment_name == str(query.experiment_name),
            )
            .delete()
        )
        self._get_session().commit()

    @override
    def get_rvs_count(self, query: RandomValuesAllQuery) -> int:
        """
        Count samples for generator config.

        Parameters
        ----------
        query : RandomValuesAllQuery
            Generator configuration.

        Returns
        -------
        int
            Number of samples.
        """
        return (
            self._get_session()
            .query(AlchemyRandomValues)
            .filter(
                AlchemyRandomValues.generator_code == query.generator_code,
                *self._experiment_name_filter(query.experiment_name),
                AlchemyRandomValues.sample_size == int(query.sample_size),
            )
            .count()
        )

    @override
    def bulk_insert_data(self, data_list: Iterable[RandomValuesModel]) -> None:
        """
        Replace all samples for generator config.

        Parameters
        ----------
        data_list : Iterable[RandomValuesModel]
            Full dataset to store.

        Returns
        -------
        None
        """
        next_sample_nums: dict[tuple[str, int, str], int] = {}
        for data in data_list:
            experiment_name = str(data.experiment_name)
            key = (data.generator_code, int(data.sample_size), experiment_name)
            if key not in next_sample_nums:
                next_sample_nums[key] = self._get_existing_samples_count(
                    generator_code=data.generator_code,
                    sample_size=int(data.sample_size),
                    experiment_name=experiment_name,
                )
            next_sample_nums[key] += 1
            self._get_session().add(
                AlchemyRandomValues(
                    generator_code=data.generator_code,
                    generator_parameters=json.dumps(data.generator_parameters),
                    sample_size=int(data.sample_size),
                    experiment_name=experiment_name,
                    sample_num=next_sample_nums[key],
                    data=data.data,
                )
            )
        self._get_session().commit()

    def insert_all_data(self, data: RandomValuesAllModel) -> None:
        """Backward-compatible bulk insert API."""
        models = [
            RandomValuesModel(
                generator_code=data.generator_code,
                generator_parameters=data.generator_parameters,
                sample_size=data.sample_size,
                experiment_name=data.experiment_name,
                data=sample,
            )
            for sample in data.data
        ]
        self.bulk_insert_data(models)

    @override
    def get_all_data(self, query: RandomValuesAllQuery) -> list[RandomValuesModel]:
        """
        Fetch all samples for generator config.

        Parameters
        ----------
        query : RandomValuesAllQuery
            Generator configuration.

        Returns
        -------
        list[RandomValuesModel]
            Ordered list of samples.
        """
        rows = (
            self._get_session()
            .query(AlchemyRandomValues)
            .filter(
                AlchemyRandomValues.generator_code == query.generator_code,
                AlchemyRandomValues.sample_size == int(query.sample_size),
                *self._experiment_name_filter(query.experiment_name),
            )
            .order_by(AlchemyRandomValues.sample_num)
            .all()
        )

        return [
            RandomValuesModel(
                generator_code=query.generator_code,
                generator_parameters=query.generator_parameters or {},
                sample_size=query.sample_size,
                experiment_name=self._model_experiment_name(row),
                data=row.data,
            )
            for row in rows
        ]

    @override
    def delete_all_data(self, query: RandomValuesAllQuery) -> None:
        """
        Delete all samples for generator config.

        Parameters
        ----------
        query : RandomValuesAllQuery
            Generator configuration.

        Returns
        -------
        None
        """
        (
            self._get_session()
            .query(AlchemyRandomValues)
            .filter(
                AlchemyRandomValues.generator_code == query.generator_code,
                AlchemyRandomValues.sample_size == int(query.sample_size),
                *self._experiment_name_filter(query.experiment_name),
            )
            .delete()
        )
        self._get_session().commit()

    @override
    def get_count_data(self, query: RandomValuesCountQuery) -> list[RandomValuesModel]:
        """
        Fetch limited number of samples.

        Parameters
        ----------
        query : RandomValuesCountQuery
            Generator config and limit.

        Returns
        -------
        list[RandomValuesModel]
            Up to `count` samples.
        """
        rows = (
            self._get_session()
            .query(AlchemyRandomValues)
            .filter(
                AlchemyRandomValues.generator_code == query.generator_code,
                AlchemyRandomValues.sample_size == int(query.sample_size),
                *self._experiment_name_filter(query.experiment_name),
            )
            .order_by(AlchemyRandomValues.sample_num)
            .limit(int(query.count))
            .all()
        )
        return [
            RandomValuesModel(
                generator_code=query.generator_code,
                generator_parameters=json.loads(row.generator_parameters),
                sample_size=query.sample_size,
                experiment_name=self._model_experiment_name(row),
                data=row.data,
            )
            for row in rows
        ]

    @staticmethod
    def _sample_num_from_experiment_name(experiment_name: str | int) -> int:
        if isinstance(experiment_name, int):
            return experiment_name
        if isinstance(experiment_name, str) and experiment_name.isdigit():
            return int(experiment_name)
        return 1

    @staticmethod
    def _model_experiment_name(row: AlchemyRandomValues) -> str:
        return row.experiment_name if row.experiment_name else str(row.sample_num)

    @staticmethod
    def _experiment_name_filter(experiment_name: str | int) -> tuple:
        if experiment_name == "":
            return ()
        return (AlchemyRandomValues.experiment_name == str(experiment_name),)

    def _get_existing_samples_count(self, generator_code: str, sample_size: int, experiment_name: str) -> int:
        return (
            self._get_session()
            .query(AlchemyRandomValues)
            .filter(
                AlchemyRandomValues.generator_code == generator_code,
                AlchemyRandomValues.sample_size == int(sample_size),
                AlchemyRandomValues.experiment_name == experiment_name,
            )
            .count()
        )
